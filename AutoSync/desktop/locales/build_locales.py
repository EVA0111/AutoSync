#!/usr/bin/env python3
"""Build locales/<code>.js from keys.txt (English, one per line) and <code>.txt
(translations in the same order). Refuses files whose line count differs.

    python build_locales.py [code ...]
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def lines(path):
    rows = path.read_text(encoding='utf-8').split('\n')
    while rows and rows[-1] == '':
        rows.pop()
    return [r.replace('\\n', '\n') for r in rows]


def build(code):
    keys = lines(HERE / 'keys.txt')
    tr = lines(HERE / 'src' / f'{code}.txt')
    if len(tr) != len(keys):
        raise SystemExit(f'{code}: {len(tr)} translations for {len(keys)} keys')
    for k, t in zip(keys, tr):
        # Shortcut keys and symbols that the text promises must survive translation.
        for mark in ('Ctrl+', '· ', '…', '→', '▶', '◀', '⟳', '✂', '↶', '↷', '⌫'):
            if mark in k and mark not in t and mark not in ('Ctrl+', '· '):
                print(f'{code}: "{k[:40]}" lost {mark!r}')
    data = dict(zip(keys, tr))
    (HERE / f'{code}.js').write_text(
        "'use strict';\n// Generated by build_locales.py from src/" + code + ".txt; edit that file, not this one.\n"
        f"(globalThis.AUTOSYNC_LOCALES=globalThis.AUTOSYNC_LOCALES||{{}}).{code}=" +
        json.dumps(data, ensure_ascii=False, indent=0) + ';\n', encoding='utf-8')
    print(f'{code}: {len(data)} strings')


if __name__ == '__main__':
    codes = sys.argv[1:] or sorted(p.stem for p in (HERE / 'src').glob('*.txt'))
    for c in codes:
        build(c)
